#!/usr/bin/env python3
"""Writes src/platform/libretro/test/realtime-bgm-fixtures.h from local ROMs.

Each fixture keeps only what the locator reads: the m4a functions with their
literal pools, and every Thumb BL in the ROM that lands in them (the entry rule
counts callers); for Pokémon GB, the head of gen2's _UpdateSound and each copy
of gen1's UpdateMusic signature, and gen2's bit tests on WRAM bytes. The test pastes these back at their offsets
into a zero ROM.
usage: bgm-fixtures.py <rom dir> > realtime-bgm-fixtures.h
"""
import struct
import sys

# name, file, (SoundMain, VSync, MPlayStart, MPlayStop) from `bgm-smoke find` with SEMANTIC=1
CASES = [
    ("firered", "Pokemon FireRed.gba", (0x081DC020, 0x081DC9D4, 0x081DD858, 0x081DD93C)),
    ("minish", "Legend of Zelda, The - The Minish Cap.gba", (0x080AF320, 0x080B0674, 0x080B0750, 0x080B0834)),
    ("heart_and_soul", "Pokemon Heart and Soul.gba", (0x0824D1C4, 0x0824DF40, 0x0817D3C4, 0x0817D5FC)),
    ("boktai", "Boktai - The Sun Is in Your Hand.gba", (0x081D513C, 0x081D5790, 0x081D65A4, 0x081D6688)),
]


def regions(entries):
    sm, vs, start, stop = (e - 0x08000000 for e in entries)
    spans = [(sm - 0x40, sm + 0x100), (vs - 0x40, vs + 0x300), (min(start, stop) - 0x40, max(start, stop) + 0x300)]
    spans.sort()
    merged = []
    for a, b in spans:
        if merged and a <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], b))
        else:
            merged.append((a, b))
    return merged


# name, file relative to the GBA dir, gen2 _UpdateSound file offset (None: gen1, found by signature)
GB_CASES = [
    ("crystal", "../gbc/Pokemon Crystal.gbc", 0x3A * 0x4000 + 0x5C),
    ("polished", "../gbc/Pokemon Polished Crystal.gbc", 0x3A * 0x4000 + 0xF1),
    ("prism", "../gbc/Pokemon Prism.gbc", 0x3A * 0x4000 + 0x51),
    ("red", "../gb/Pokemon - Red Version (USA, Europe) (SGB Enhanced).gb", None),
    ("brown", "../gb/Pokemon Brown.gb", None),
]
GEN1_HEAD = bytes([0x0E, 0x00, 0x06, 0x00, 0x21])
GEN1_TAIL = bytes([0x09, 0x7E, 0xA7])


def gb_slices(rom, entry):
    if entry is not None:
        # Plus every `ld a,[n]; bit b,a` in the bank: where the options byte is found.
        bank = entry // 0x4000 * 0x4000
        tests = [(a, a + 5) for a in range(bank, bank + 0x4000 - 5)
                 if rom[a] == 0xFA and rom[a + 3] == 0xCB and rom[a + 4] & 0xC7 == 0x47
                 and not entry <= a < entry + 0xB0]
        return [(entry, entry + 0xB0)] + tests
    return [(o, o + 10) for o in range(0x4000, len(rom) - 10)
            if rom[o:o + 5] == GEN1_HEAD and rom[o + 7:o + 10] == GEN1_TAIL]


def bl_sites(rom, spans):
    sites = []
    for off in range(0, len(rom) - 3, 2):
        hi, lo = struct.unpack_from("<HH", rom, off)
        if hi & 0xF800 != 0xF000 or lo & 0xF800 != 0xF800:
            continue
        o = ((hi & 0x7FF) << 21)
        o = (o - (1 << 32) if o & (1 << 31) else o) >> 9
        target = off + 4 + (o | ((lo & 0x7FF) << 1))
        if any(a <= target < b for a, b in spans) and not any(a <= off < b for a, b in spans):
            sites.append((off, off + 4))
    return sites


def main():
    out = ["// Generated by libretro-build/tools/bgm-fixtures.py from the developer's ROMs.",
           "// Only sound driver code (m4a functions and their callers, Pokémon GB engine heads); no game content.",
           "#ifndef REALTIME_BGM_FIXTURES_H", "#define REALTIME_BGM_FIXTURES_H", "",
           "#include <stddef.h>", "#include <stdint.h>", "",
           "struct BgmFixtureSlice { uint32_t offset; uint32_t length; const uint8_t* bytes; };",
           "struct BgmFixture {", "\tconst char* name;", "\tuint32_t romSize;",
           "\tconst struct BgmFixtureSlice* slices;", "\tsize_t count;",
           "\tuint32_t soundMain, soundVSync, mplayStart, mplayStop;", "};", ""]
    table = []
    for name, file, entries in CASES:
        rom = open(f"{sys.argv[1]}/{file}", "rb").read()
        spans = regions(entries)
        slices = spans + bl_sites(rom, spans)
        refs = []
        for i, (a, b) in enumerate(slices):
            data = ", ".join(f"0x{x:02X}" for x in rom[a:b])
            out.append(f"static const uint8_t {name}_{i}[] = {{ {data} }};")
            refs.append(f"\t{{ 0x{a:X}, {b - a}, {name}_{i} }},")
        out.append(f"static const struct BgmFixtureSlice {name}_slices[] = {{")
        out += refs
        out.append("};")
        e = ", ".join(f"0x{x:08X}" for x in entries)
        table.append(f"\t{{ \"{name}\", 0x{len(rom):X}, {name}_slices, sizeof({name}_slices) / sizeof({name}_slices[0]), {e} }},")
    out.append("static const struct BgmFixture bgmFixtures[] = {")
    out += table
    out += ["};", "", "struct GbFixture { const char* name; uint32_t romSize; const struct BgmFixtureSlice* slices; size_t count; };", ""]
    table = []
    for name, file, entry in GB_CASES:
        rom = open(f"{sys.argv[1]}/{file}", "rb").read()
        refs = []
        for i, (a, b) in enumerate(gb_slices(rom, entry)):
            data = ", ".join(f"0x{x:02X}" for x in rom[a:b])
            out.append(f"static const uint8_t {name}_{i}[] = {{ {data} }};")
            refs.append(f"\t{{ 0x{a:X}, {b - a}, {name}_{i} }},")
        out.append(f"static const struct BgmFixtureSlice {name}_slices[] = {{")
        out += refs
        out.append("};")
        table.append(f"\t{{ \"{name}\", 0x{len(rom):X}, {name}_slices, sizeof({name}_slices) / sizeof({name}_slices[0]) }},")
    out.append("static const struct GbFixture gbFixtures[] = {")
    out += table
    out += ["};", "", "#endif", ""]
    sys.stdout.write("\n".join(out))


main()
